-- ================================================================
-- PHASE 3: FACT TABLE — matches_clean
--
-- PURPOSE:
-- Create a cleaned, type-enforced version of raw_matches that all
-- downstream queries use. Never query raw_matches directly after
-- this step — always use matches_clean.
--
-- KEY DECISIONS:
--
-- 1. CAST(x AS SIGNED) not CAST(x AS INTEGER)
--    MySQL's CAST() uses SIGNED/UNSIGNED for integers, not INTEGER.
--    INTEGER is SQLite syntax and does not work in MySQL.
--
-- 2. NULLIF(home_goals, '') before CAST
--    NULLIF(x, '') returns NULL if x is an empty string, otherwise
--    returns x unchanged. This is critical: CAST('' AS SIGNED) in
--    MySQL returns 0, not NULL. Without NULLIF, every upcoming match
--    would appear to have ended 0-0, corrupting all standings
--    calculations that filter on is_completed = 1.
--
-- 3. LEFT(match_date, 10) not DATE(match_date)
--    The raw match_date from openfootball is a plain YYYY-MM-DD
--    string, so LEFT(match_date, 10) safely extracts the date.
--    If using API-Football, dates come as full ISO 8601 strings
--    like "2026-06-14T19:00:00+00:00" — MySQL's DATE() function
--    can fail on the T separator and timezone offset, making LEFT()
--    the safer choice regardless of source format.
--
-- 4. group_name LIKE 'Group%' for stage_category
--    openfootball stores group names as "Group A", "Group B" etc.
--    directly in the group_name field (unlike round which says
--    "Matchday 1"). LIKE 'Group%' cleanly separates group stage
--    from knockout stage matches for the ad-slot tier logic.
-- ================================================================

CREATE TABLE matches_clean AS
SELECT
    CAST(fixture_id AS SIGNED)                    AS fixture_id,
    LEFT(match_date, 10)                          AS match_date,
    TRIM(round)                                   AS round,
    TRIM(group_name)                              AS group_name,
    TRIM(status_short)                            AS status_short,
    TRIM(home_team)                               AS home_team,
    TRIM(away_team)                               AS away_team,
    CAST(NULLIF(home_goals, '') AS SIGNED)        AS home_goals,
    CAST(NULLIF(away_goals, '') AS SIGNED)        AS away_goals,

    -- is_completed: 1 for finished matches, 0 for upcoming.
    -- Used as a filter in every downstream aggregation query to
    -- ensure we only calculate stats from played matches.
    CASE WHEN status_short = 'FT' THEN 1 ELSE 0 END AS is_completed,

    -- stage_category: classifies each match as Group Stage or
    -- Knockout Stage. Knockout matches get a higher ad-slot tier
    -- in the engagement analysis because elimination stakes drive
    -- significantly higher viewership than group stage matches.
    CASE
        WHEN group_name LIKE 'Group%' THEN 'Group Stage'
        ELSE 'Knockout Stage'
    END AS stage_category

FROM raw_matches;

-- VERIFY: null_goals_rows should equal upcoming count exactly.
-- If null_goals_rows < upcoming, NULLIF did not work correctly
-- and some unplayed matches are showing as 0-0.
SELECT
    COUNT(*)                                            AS total_fixtures,
    SUM(is_completed)                                   AS completed,
    COUNT(*) - SUM(is_completed)                        AS upcoming,
    SUM(CASE WHEN home_goals IS NULL THEN 1 ELSE 0 END) AS null_goals_rows
FROM matches_clean;
-- Expected: total=104, completed=73, upcoming=31, null_goals_rows=31


-- ================================================================
-- PHASE 4: INTERMEDIATE TABLE — team_match_stats
--
-- PURPOSE:
-- Transform match-level data (one row per match) into team-level
-- data (one row per team per match). This is the critical step
-- that makes standings aggregation possible.
--
-- WHY UNION ALL?
-- Each match involves two teams. To calculate a team's total points,
-- wins, goals etc., we need each team's result from their own
-- perspective. A single match row has home_team and away_team —
-- we need to "unfold" this into two rows, one for each team.
-- UNION ALL creates the home team's row in the first SELECT and
-- the away team's mirror-image row in the second SELECT, then
-- stacks them. Result: 73 completed matches × 2 = 146 rows.
--
-- WHY UNION ALL NOT UNION?
-- UNION removes duplicate rows. UNION ALL keeps all rows including
-- duplicates. We want ALL rows here — we are not looking for
-- unique values, we are creating two intentionally different
-- perspectives of the same match. UNION would potentially drop
-- rows where both teams had identical stats (e.g. two 0-0 draws
-- in the same group), corrupting the standings.
--
-- WHY CASE WHEN INSIDE SUM()?
-- This is the standard SQL pattern for conditional counting.
-- Instead of using COUNT() with a WHERE clause (which would
-- require a separate query per metric), CASE WHEN returns 1 or 0
-- for each row, and SUM() adds them up. One pass through the data
-- gives us wins, draws, and losses simultaneously.
-- ================================================================

CREATE TABLE team_match_stats AS

-- HOME TEAM PERSPECTIVE
-- For the home team: goals_for = home_goals, goals_against = away_goals
SELECT
    fixture_id,
    match_date,
    stage_category,
    home_team    AS team,
    away_team    AS opponent,
    home_goals   AS goals_for,
    away_goals   AS goals_against,
    CASE
        WHEN home_goals > away_goals THEN 3  -- win = 3 points
        WHEN home_goals = away_goals THEN 1  -- draw = 1 point
        ELSE 0                               -- loss = 0 points
    END AS points,
    CASE WHEN home_goals > away_goals THEN 1 ELSE 0 END AS win,
    CASE WHEN home_goals = away_goals THEN 1 ELSE 0 END AS draw,
    CASE WHEN home_goals < away_goals THEN 1 ELSE 0 END AS loss
FROM matches_clean
WHERE is_completed = 1

UNION ALL

-- AWAY TEAM PERSPECTIVE (mirror image)
-- For the away team: goals_for = away_goals, goals_against = home_goals
-- Everything is flipped — what was "home" is now "opponent"
SELECT
    fixture_id,
    match_date,
    stage_category,
    away_team    AS team,
    home_team    AS opponent,
    away_goals   AS goals_for,
    home_goals   AS goals_against,
    CASE
        WHEN away_goals > home_goals THEN 3
        WHEN away_goals = home_goals THEN 1
        ELSE 0
    END AS points,
    CASE WHEN away_goals > home_goals THEN 1 ELSE 0 END AS win,
    CASE WHEN away_goals = home_goals THEN 1 ELSE 0 END AS draw,
    CASE WHEN away_goals < home_goals THEN 1 ELSE 0 END AS loss
FROM matches_clean
WHERE is_completed = 1;

-- VERIFY: Should be 73 × 2 = 146 rows
SELECT COUNT(*) AS total_rows FROM team_match_stats;


