-- ================================================================
-- PHASE 8: UPSET ANALYSIS — high_engagement_matches
--
-- PURPOSE:
-- Join completed match results with pre-tournament Elo ratings to
-- identify upset matches and assign ad-slot tiers. This table
-- directly answers the core business question: which matches are
-- the highest-value advertising inventory?
--
-- BUSINESS LOGIC:
-- Upsets generate the highest social media engagement, replay
-- demand, and viewership spikes of any match type. A broadcaster
-- that can identify high-upset-probability matches in advance can
-- charge premium CPM rates for those ad slots. This table
-- quantifies "upset magnitude" using Elo gap as the measure.
--
-- KEY CALCULATIONS:
-- elo_gap = ABS(home_elo - away_elo)
--   Measures how mismatched the two teams were on paper.
--   A gap of 100+ points means one team was a clear favourite.
--   The larger the gap with the underdog winning, the bigger
--   the upset and the higher the expected viewership spike.
--
-- upset threshold = 100 Elo points
--   Standard threshold in football analytics for "clear favourite".
--   Below 100 points difference = competitive match, result not
--   surprising regardless of who wins.
--
-- AD SLOT TIER LOGIC:
--   TIER 1 - Premium: Upset in a knockout stage match
--            (highest stakes + biggest surprise = maximum value)
--   TIER 2 - High: Upset in group stage
--            (big surprise but lower elimination stakes)
--   TIER 3 - Elevated: No upset but knockout stage
--            (elimination stakes alone drive premium viewership)
--   TIER 4 - Standard: Expected result in group stage
--            (baseline inventory)
--
-- WHY TWO JOINS TO elo_ratings?
-- Each match has two teams. We need Elo ratings for both home and
-- away teams simultaneously to calculate the gap. This requires
-- joining elo_ratings twice — once aliased as 'eh' (elo home)
-- and once as 'ea' (elo away). Each join matches on a different
-- column (home_team vs away_team).
-- ================================================================

CREATE TABLE high_engagement_matches AS
SELECT
    m.fixture_id,
    m.match_date,
    m.round,
    m.group_name,
    m.stage_category,
    m.home_team,
    m.away_team,
    m.home_goals,
    m.away_goals,
    eh.elo_rating                      AS home_elo,
    ea.elo_rating                      AS away_elo,
    ABS(eh.elo_rating - ea.elo_rating) AS elo_gap,

    CASE
        WHEN m.home_goals > m.away_goals
             AND eh.elo_rating < ea.elo_rating - 100
        THEN 'UPSET: Lower-rated home team won'

        WHEN m.away_goals > m.home_goals
             AND ea.elo_rating < eh.elo_rating - 100
        THEN 'UPSET: Lower-rated away team won'

        WHEN m.home_goals > m.away_goals
        THEN 'Expected: Home win'

        WHEN m.away_goals > m.home_goals
        THEN 'Expected: Away win'

        ELSE 'Draw'
    END AS result_classification,

    CASE
        WHEN (m.home_goals > m.away_goals AND eh.elo_rating < ea.elo_rating - 100)
          OR (m.away_goals > m.home_goals AND ea.elo_rating < eh.elo_rating - 100)
        THEN
            CASE WHEN m.stage_category = 'Knockout Stage' THEN 'TIER 1 - Premium'
                 ELSE 'TIER 2 - High'
            END
        WHEN m.stage_category = 'Knockout Stage' THEN 'TIER 3 - Elevated'
        ELSE 'TIER 4 - Standard'
    END AS ad_slot_tier

FROM matches_clean m
JOIN elo_ratings eh ON m.home_team = eh.team_name
JOIN elo_ratings ea ON m.away_team = ea.team_name
WHERE m.is_completed = 1;

-- VIEW CONFIRMED UPSETS ranked by Elo gap (biggest surprises first)
SELECT
    match_date,
    home_team,
    away_team,
    home_goals,
    away_goals,
    home_elo,
    away_elo,
    elo_gap,
    result_classification,
    ad_slot_tier
FROM high_engagement_matches
WHERE result_classification LIKE 'UPSET%'
ORDER BY elo_gap DESC;

