-- ================================================================
-- PHASE 6: RANKED STANDINGS — final_standings
--
-- PURPOSE:
-- Add a dynamic group_rank column to group_standings using a
-- window function. Each team gets a rank (1–4) within their group
-- based on FIFA tiebreaker rules: points first, then goal
-- difference, then goals scored.
--
-- WHY A WINDOW FUNCTION INSTEAD OF A SUBQUERY?
-- A correlated subquery approach would require a separate COUNT
-- query for every single row — highly inefficient. A window function
-- processes all rows in one pass and is the standard modern SQL
-- approach for this type of ranking problem.
--
-- WHY PARTITION BY group_name?
-- Without PARTITION BY, RANK() would rank all 48 teams globally
-- (1 to 48). PARTITION BY group_name resets the ranking for each
-- group independently, giving us ranks 1–4 within each group.
-- Think of it as "GROUP BY for window functions" — it defines the
-- window (subset of rows) that each rank is calculated within.
--
-- WHY RANK() NOT ROW_NUMBER()?
-- ROW_NUMBER() always gives unique sequential numbers (1,2,3,4).
-- RANK() gives tied teams the same rank and skips the next number
-- (e.g. two teams tied for 2nd both get rank 2, next team gets 4).
-- FIFA rules can result in ties, so RANK() is more accurate here.
--
-- NOTE ON MYSQL COMPATIBILITY:
-- Window functions require MySQL 8.0+. If you see the error
-- "FUNCTION worldcup.RANK does not exist", your MySQL version
-- is below 8.0. Run SELECT VERSION(); to check.
-- ================================================================

CREATE TABLE final_standings AS
SELECT
    group_name,
    team,
    played,
    wins,
    draws,
    losses,
    goals_for,
    goals_against,
    goal_difference,
    points,

    -- THE WINDOW FUNCTION
    -- PARTITION BY: calculate rank separately for each group
    -- ORDER BY: FIFA official tiebreaker sequence
    RANK() OVER (
        PARTITION BY group_name
        ORDER BY points DESC, goal_difference DESC, goals_for DESC
    ) AS group_rank,

    -- Business interpretation for dashboard display
    CASE
        WHEN RANK() OVER (PARTITION BY group_name ORDER BY points DESC, goal_difference DESC, goals_for DESC) = 1
        THEN 'Group Leader'
        WHEN RANK() OVER (PARTITION BY group_name ORDER BY points DESC, goal_difference DESC, goals_for DESC) = 2
        THEN 'Qualification Zone'
        WHEN RANK() OVER (PARTITION BY group_name ORDER BY points DESC, goal_difference DESC, goals_for DESC) = 3
        THEN 'Best-Third Contender'
        ELSE 'Eliminated'
    END AS qualification_status

FROM group_standings;

-- VERIFY: 12 group leaders, one per group
SELECT group_name, team, points, group_rank, qualification_status
FROM final_standings
WHERE group_rank = 1
ORDER BY group_name;


